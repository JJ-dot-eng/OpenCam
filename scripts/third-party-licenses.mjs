// 프로그램에 함께 들어가는 Rust·npm 부품의 저작권 표시와 라이선스 전문을 THIRD_PARTY_LICENSES.txt 하나로 모은다.
// 부품을 바꾸거나 버전을 올리면 다시 실행: node scripts/third-party-licenses.mjs
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const LICENSE_FILE = /^(licen[sc]e|copying|notice|copyright|unlicense)([-._].*)?$/i;

function licenseTexts(dir) {
  if (!existsSync(dir)) return [];
  const files = [];
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    const st = statSync(path);
    if (st.isFile() && LICENSE_FILE.test(name)) files.push(path);
    else if (st.isDirectory() && /^licen[sc]es?$/i.test(name)) {
      for (const sub of readdirSync(path).sort()) if (statSync(join(path, sub)).isFile()) files.push(join(path, sub));
    }
  }
  return files.map((f) => readFileSync(f, "utf8").replace(/\r\n/g, "\n").trim());
}

// Rust: Windows 빌드에서 실제로 링크되는 일반 의존성만 (build·dev 의존성 제외)
function rustPackages() {
  const meta = JSON.parse(
    execFileSync("cargo", ["metadata", "--format-version", "1", "--filter-platform", "x86_64-pc-windows-msvc",
      "--manifest-path", join(root, "src-tauri", "Cargo.toml")], { encoding: "utf8", maxBuffer: 256 * 1024 * 1024 }),
  );
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const pkgs = new Map(meta.packages.map((p) => [p.id, p]));
  const seen = new Set();
  const queue = [meta.resolve.root];
  while (queue.length) {
    const id = queue.shift();
    for (const dep of nodes.get(id).deps) {
      if (!dep.dep_kinds.some((k) => k.kind === null) || seen.has(dep.pkg)) continue;
      seen.add(dep.pkg);
      queue.push(dep.pkg);
    }
  }
  return [...seen].map((id) => {
    const p = pkgs.get(id);
    let texts = licenseTexts(dirname(p.manifest_path));
    // 배포본에 라이선스 파일이 빠진 crate는 원래 저장소에서 받아 둔 scripts/licenses/<이름>.txt를 쓴다
    for (const name of [p.name, p.name.replace(/-(sys|macros)$/, "")]) {
      const extra = join(root, "scripts", "licenses", `${name}.txt`);
      if (!texts.length && existsSync(extra)) texts = [readFileSync(extra, "utf8").replace(/\r\n/g, "\n").trim()];
    }
    return { name: p.name, version: p.version, license: p.license || "", url: p.repository || "", texts };
  });
}

// npm: 화면 코드에 묶여 들어가는 의존성만 (devDependencies 제외)
function npmPackages() {
  const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
  return Object.entries(lock.packages)
    .filter(([path, p]) => path.startsWith("node_modules/") && !p.dev && !p.devOptional)
    .map(([path, p]) => {
      const name = path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length);
      const pj = JSON.parse(readFileSync(join(root, path, "package.json"), "utf8"));
      const url = typeof pj.repository === "string" ? pj.repository : pj.repository?.url || "";
      return { name, version: p.version, license: p.license || pj.license || "", url, texts: licenseTexts(join(root, path)) };
    });
}

const all = [...rustPackages(), ...npmPackages()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

// 같은 라이선스 전문을 쓰는 부품끼리 묶어 한 번만 싣는다
const groups = new Map();
for (const p of all) {
  const key = p.texts.join("\n\f\n");
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(p);
}

const out = [
  "OpenCam third-party licenses",
  "",
  "OpenCam(GPL-3.0-or-later)에 함께 들어가는 부품의 저작권 표시와 라이선스 전문입니다.",
  "Copyright notices and license texts of the components bundled with OpenCam.",
  "Generated by scripts/third-party-licenses.mjs. Do not edit by hand.",
  "",
];
for (const [key, list] of groups) {
  out.push("=".repeat(78));
  for (const p of list) out.push(`${p.name} ${p.version}${p.license ? ` (${p.license})` : ""}${p.url ? ` - ${p.url}` : ""}`);
  out.push("-".repeat(78));
  out.push(key ? key.replace(/\n\f\n/g, `\n\n${"-".repeat(78)}\n\n`) : "(이 부품의 배포본에는 라이선스 파일이 없습니다. 위 SPDX 라이선스 표기를 따릅니다.)");
  out.push("");
}
writeFileSync(join(root, "THIRD_PARTY_LICENSES.txt"), out.join("\n"));
const missing = all.filter((p) => !p.texts.length);
console.log(`${all.length} packages, ${groups.size} license groups, ${missing.length} without license files`);
for (const p of missing) console.log(`  no license file: ${p.name} ${p.version} (${p.license})`);
